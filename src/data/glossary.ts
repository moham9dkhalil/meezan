export function findMatchingTerm(text: string): AccountingTerm | undefined {
  const clean = text.trim().toLowerCase();
  return ACCOUNTING_GLOSSARY.find((item) => {
    if (item.term.toLowerCase() === clean) return true;
    if (item.aliases?.some((a) => a.toLowerCase() === clean)) return true;
    return false;
  });
}
