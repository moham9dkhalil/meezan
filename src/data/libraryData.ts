import { Book, BookChapter } from "../types";

// Helper generator to build 105 complete chapters for each book
function generateChaptersForBook(
  callNumber: string,
  title: string,
  category: string,
  baseChapters: BookChapter[],
  targetTotal: number = 105
): BookChapter[] {
  const result: BookChapter[] = [...baseChapters];
  const startIdx = baseChapters.length;
  const topics = getTopicListForBook(callNumber);

  for (let i = startIdx; i < targetTotal; i++) {
    const chapNum = i + 1;
    const topicTitle = topics[i - startIdx] || getDefaultTopicTitle(callNumber, chapNum);

    result.push({
      t: `الفصل ${chapNum}: ${topicTitle}`,
      sections: generateChapterSections(title, topicTitle, chapNum, category)
    });
  }

  return result;
}

