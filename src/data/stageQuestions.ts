import { STAGES_DATA } from "./curriculum";
import { FlashCard } from "../types";

export interface StageQuestionCard extends FlashCard {
  stageId: number;
  stageName: string;
  lessonIdx: number;
  lessonTitle: string;
  questionNum: number;
  answer: string;
  exText?: string;
  keys?: string[];
}

// Generate 10 Questions per Lesson for all 32 Stages
export function getStageQuestionCards(stageId?: number): StageQuestionCard[] {
  const cards: StageQuestionCard[] = [];
  const stagesToProcess = stageId
    ? STAGES_DATA.filter((s) => s.id === stageId)
    : STAGES_DATA;

  stagesToProcess.forEach((stage) => {
    stage.lessons.forEach((lesson, lIdx) => {
      const unitNum = lIdx + 1;
      const cleanTitle = lesson.title.replace(/^الوحدة \d+: /, "");
      const keyPoints = lesson.keys ? lesson.keys.join(" • ") : "الربط بين المفهوم النظري والتطبيق العملي المحاسبي";

      // 10 Detailed Questions for each lesson unit
      const questionsData = [
        {
          num: 1,
          q: `[س1 - المفهوم الجوهري]: ما هو التعريف والدور الأساسي المباشر لـ "${cleanTitle}" في النظام المحاسبي؟`,
          a: lesson.body,
          ex: lesson.exText || "تحديد وطباعة المستندات المؤيدة وحفظها في الأرشيف المالي.",
          hint: keyPoints
        },
        {
          num: 2,
          q: `[س2 - التوجيه المحاسبي]: كيف يتم صياغة القيد اليومي المزدوج والتوجيه الصحيح لعمليات "${cleanTitle}"؟`,
          a: `يتم إعداد القيد المحاسبي لـ "${cleanTitle}" وفق قاعدة القيد المزدوج بالتساوي التام بين الطرفين:\n\n• الطرف المدين: حـ/ الحساب المباشر المستفيد بـ (${cleanTitle}).\n• الطرف الدائن: حـ/ الحساب المقابل (النقدية، البنك، الموردون، أو العملاء).\n\nصيغة القيد القياسي:\nمن حـ/ الحساب المعني بـ ${cleanTitle}\n   إلى حـ/ النقدية أو الحساب الوسيط`,
          ex: "مطابقة طرفي القيد والتحقق من التوازن الحسابي في دفتر اليومية.",
          hint: "المدين = الاستخدامات والأصول • الدائن = المصادر والالتزامات"
        },
        {
          num: 3,
          q: `[س3 - الأثر المالي والميزانية]: ما هو الأثر المباشر لـ "${cleanTitle}" على قائمة الدخل وقائمة المركز المالي؟`,
          a: `تنعكس معاملات "${cleanTitle}" على القوائم المالية كما يلي:\n\n1. قائمة الدخل: تسجيل الإيرادات أو المصروفات المترتبة لتحقيق صافي ربح عادل للفترة.\n2. قائمة المركز المالي: تعديل قيم الأصول والالتزامات المقابلة للحفاظ على توازن معادلة الميزانية (الأصول = الالتزامات + حقوق الملكية).`,
          ex: "التحقق من توازن الميزانية بعد ترحيل قيد العملية.",
          hint: "معادلة الميزانية الذهبية: الأصول = الالتزامات + حقوق الملكية"
        },
        {
          num: 4,
          q: `[س4 - المستندات والوثائق]: ما هي الدورة المستندية والوثائق الواجب توفرها قبل تسجيل "${cleanTitle}"؟`,
          a: `تتطلب المعالجة المحاسبية السليمة لـ "${cleanTitle}" توفر الدورة المستندية التالية:\n\n1. الفاتورة الضريبية الرسمية وطلب المشتريات/الخدمة.\n2. إذن التسليم أو محضر الفحص والاستلام.\n3. سند القبض أو الصرف المعتمد من المدير المالي صاحب الصلاحية.`,
          ex: "إرفاق أصل الفاتورة بسند الصرف المالي وتوقيع المراجع.",
          hint: "لا قيد محاسبي بدون مستند رسمي مؤيد ومعتمد"
        },
        {
          num: 5,
          q: `[س5 - المعايير الدولية IFRS]: كيف تنظم معايير التقارير المالية الدولية المعالجة المحاسبية لـ "${cleanTitle}"؟`,
          a: `وفق معايير التقارير المالية الدولية (IFRS):\n• يتم الاعتراف المباشر والموضوعي فور تحقق شروط البند.\n• القياس الأولي بالتكلفة المباشرة والقياس اللاحق بالقيمة العادلة أو التكلفة المطفأة.\n• الإفصاح الشفاف بكافة الملاحظات المتممة للقوائم المالية.`,
          ex: "العرض العادل في الميزانية مع إفصاح كامل في الإيضاحات.",
          hint: "القياس الموضوعي + العرض العادل + الإفصاح الكافي"
        },
        {
          num: 6,
          q: `[س6 - التسويات الجردية]: كيف تتم التسوية الجردية وتطبيق مبدأ الاستحقاق الخاص بـ "${cleanTitle}" نهاية الفترة؟`,
          a: `في نهاية السنة المالية (31 ديسمبر)، يتم فحص وتعديل رصيد "${cleanTitle}":\n\n• إثبات المصروفات أو الإيرادات المستحقة غير المسددة.\n• تسوية المصروفات والإيرادات المقدمة لنقل ما يخص السنة المالية الحالية لقائمة الدخل.\n• تدوير المتبقي كأصل أو التزام بالميزانية العمومية.`,
          ex: "تسجيل قيود التسوية الجردية قبل إقفال الحسابات النهائية.",
          hint: "تحميل الفترة بما يخصها فعلياً من إيراد ومصروف"
        },
        {
          num: 7,
          q: `[س7 - الرقابة والضبط الداخلي]: ما هي إجراءات الضبط والرقابة الداخلية المعتمدة لحماية عمليات "${cleanTitle}"؟`,
          a: `تشمل إجراءات الرقابة الداخلية الخاصة بـ "${cleanTitle}":\n\n1. الفصل التام بين موظف الإدخال ومسؤول الاعتماد المالي.\n2. وضع مصفوفة صلاحيات مالية محددة لكل مسمى وظيفي.\n3. إجراء المطابقات الدورية وسجلات المتابعة والتدقيق المستقل.`,
          ex: "فحص العينات الفجائية من قبل لجنة التدقيق الداخلي.",
          hint: "الفصل بين الصلاحيات + الصلاحيات المحددة + التدقيق المستقل"
        },
        {
          num: 8,
          q: `[س8 - تصحيح الأخطاء]: ما هي الأخطاء المحاسبية الشائعة عند تطبيق "${cleanTitle}" وكيف تصحح نظامياً؟`,
          a: `تنشأ الأخطاء من السهو أو التوجيه الخاطئ. وتصحح نظامياً بالطرق المعتمدة:\n\n• الطريقة المطولة: إلغاء القيد الخاطئ بقيد عكسي بالكامل، ثم إثبات القيد الصحيح.\n• الطريقة المختصرة: عمل قيد تسوية مباشر يعالج الفرق والخطأ فور اكتشافه دون إرباك الحسابات.`,
          ex: "إرفاق مذكرة شرح وتصحيح معتمدة من المراجع الخارجي.",
          hint: "يمنع الشطب بالدفاتر وتصحح الأخطاء بقيود دقيقة"
        },
        {
          num: 9,
          q: `[س9 - الحالة العملية والتطبيق]: اذكر حالة تطبيقية واقعية تجسد كيفية التعامل مع "${cleanTitle}" في الشركات؟`,
          a: lesson.exText || `حالة عملية: حدوث حركة مالية حقيقية متعلقة بـ (${cleanTitle}).\n\nخطوات المعالجة الميدانية:\n1. استلام ومراجعة مستندات العملية.\n2. إدخال القيد المتوازن بالنظام المحاسبي.\n3. التترحيل التلقائي لدفتر الأستاذ وميزان المراجعة.\n4. استخراج التقرير المالي المحدث.`,
          ex: lesson.exText || "تأكيد صحة العملية وترحيلها لدفتر الأستاذ.",
          hint: "التطبيق الميداني في بيئة العمل الحقيقية"
        },
        {
          num: 10,
          q: `[س10 - الملخص الذهبي والتقييم]: ما هي القواعد الخمس الذهبية التي يجب على المحاسب التأكد منها بخصوص "${cleanTitle}"؟`,
          a: `القواعد الخمس الذهبية لـ "${cleanTitle}":\n\n1. التثبت من وجود مستند رسمي معتمد.\n2. التوجيه المزدوج المتوازن (مدين = دائن).\n3. التترحيل الفوري للأستاذ العام والفرعي.\n4. إجراء قيود التسوية الجردية وفق الاستحقاق.\n5. العرض والإفصاح العادل بالقوائم المالية.`,
          ex: "التأكد من اكتمال القواعد الخمس يضمن احترافية العمل المحاسبي.",
          hint: "التوثيق • التوازن • التترحيل • التسوية • الإفصاح"
        }
      ];

      questionsData.forEach((qd) => {
        cards.push({
          ar: qd.q,
          en: `Stage ${stage.id} - Lesson ${unitNum}: ${cleanTitle}`,
          cat: `🎓 مرحلة ${stage.id}: ${stage.name}`,
          hint: qd.hint,
          answer: qd.a,
          exText: qd.ex,
          stageId: stage.id,
          stageName: stage.name,
          lessonIdx: lIdx,
          lessonTitle: cleanTitle,
          questionNum: qd.num,
          keys: lesson.keys
        });
      });
    });
  });

  return cards;
}
