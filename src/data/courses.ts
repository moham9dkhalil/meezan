import { Course, CourseModule, CourseTopic } from "../types";

// Helper to generate 100 structured, high-quality educational units (10 modules x 10 units) per course
function generate100ModulesForCourse(
  courseId: string,
  moduleDefs: {
    title: string;
    sub: string;
    icon: string;
    units: {
      title: string;
      sub: string;
      formula?: string;
      concept: string;
      points: string[];
      quizQ: string;
      quizOpts: string[];
      quizAns: number;
      quizExp: string;
    }[];
  }[]
): CourseModule[] {
  return moduleDefs.map((modDef, mIdx) => {
    const modNum = mIdx + 1;
    const topics: CourseTopic[] = modDef.units.map((unit, uIdx) => {
      const uNum = uIdx + 1;
      const globalUnitIndex = (modNum - 1) * 10 + uNum;
      
      const expandedContent = `📌 أولاً: المفهوم والإطار النظري التأسيسي (Theoretical Concept & Standard Framework)
تُعد الوحدة المتقدمة رقم (${globalUnitIndex}) تحت عنوان "${unit.title}" من أهم المحاور الأكاديمية والمهنية في مسار ${courseId.toUpperCase()}.
${unit.concept}

تستند هذه الوحدة إلى المبادئ المحاسبية المعترف بها دولياً (IFRS / US GAAP)، حيث يتم تحليل المعاملات بناءً على جوهر المعاملة المالي (Substance over Form) وليس النموذج القانوني المجرّد فقط.

📌 ثانياً: التطبيق الميداني وقيود اليومية المعيارية (Practical Accounting Journal Entries)
عند إثبات وتنفيذ المعاملة في الدفاتر والسجلات المالية، يتطلب الأمر تطبيق القيود المحاسبية التالية:

• القيد الأول (الإثبات الأولي / Initial Recognition):
من حـ/ ${unit.title} (طرف مدين - أصول / مصاريف)
   إلى حـ/ النقدية أو البنك أو الالتزامات المستحقة (طرف دائن)

• القيد الثاني (التسوية الدورية / Periodic Adjustment & Closing):
من حـ/ مخصص التسوية أو أرباح وخسائر الفترة
   إلى حـ/ الحساب التجميعي المرتبط أو مجمع الهبوط

📌 ثالثاً: الأثر التفصيلي على القوائم المالية (Impact on Financial Statements)
1. قائمة المركز المالي (الميزانية العمومية): تؤثر المعاملة مباشرة على متطلبات الرأس العامل (Working Capital)، حيث تعزز شفافية إفصاح الأصول والالتزامات القصيرة والطويلة الأجل.
2. قائمة الدخل (الأرباح والخسائر): يظهر الأثر المباشر على الأرباح التشغيلية EBITDA وصافي دخل الدورة المالية بعد احتساب العبء الضريبي والمالي.
3. قائمة التدفقات النقدية: تتأثر الأنشطة التشغيلية أو الاستثمارية أو التمويلية تبعاً لنوع التدفق النقدي المستلم أو المدفوع.

📌 رابعاً: ضوابط الرقابة الداخلية وإجراءات التدقيق (Internal Controls & Audit Checkpoints)
• التأكد من وجود الدورة المستندية الكاملة (المستندات المؤيدة، الفواتير المعتمدة، والموافقات الصريحة).
• تطبيق الفصل بين المهام (Segregation of Duties) لمنع التعارض والاحتيال المالي.
• إجراء المطابقات الدورية ومراجعة فروق التقييم مع ميزان المراجعة التحليلي قبل إقفال الفترات المالية.`;

      const defaultPoints = [
        `فهم واستيعاب المبدأ المالي والمهني المباشر لـ ${unit.title}`,
        "إتقان قيود اليومية للطرفين المدين والدائن والتسويات الدورية",
        "تحليل الأثر المالي المباشر على قائمة المركز المالي وقائمة الدخل",
        "الالتزام بمتطلبات الإفصاح والشفافية وفق معايير IFRS / US GAAP",
        "تطبيق إجراءات الرقابة الداخلية ومنع الأخطاء والاحتيال المحاسبي"
      ];

      return {
        id: `top-${courseId}-m${modNum}-u${uNum}`,
        title: `الوحدة ${globalUnitIndex}: ${unit.title}`,
        sub: unit.sub,
        formula: unit.formula || `المعادلة المعيارية = القياس الأولي + التسويات الدورية - المخصصات والالتزامات (${globalUnitIndex})`,
        content: expandedContent,
        keyPoints: unit.points && unit.points.length >= 3 ? [...unit.points, ...defaultPoints.slice(unit.points.length)] : defaultPoints,
        quiz: [
          {
            q: unit.quizQ,
            opts: unit.quizOpts,
            ans: unit.quizAns,
            exp: `${unit.quizExp} (التعليل العلمي: استناداً إلى معايير المحاسبة والتقرير المالي المعنية بتقييم وإثبات هذه المعاملة بشكل دقيق).`
          }
        ]
      };
    });

    return {
      id: `${courseId}-mod-${modNum}`,
      title: `الموديول ${modNum}: ${modDef.title}`,
      sub: modDef.sub,
      icon: modDef.icon,
      topics
    };
  });
}

